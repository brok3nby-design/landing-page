// Copy WRFM's live-broadcast schedule from the station's source repo into this site, so the desk radio can
// tune in to exactly what WRFM 97.1 is playing right now (same clock-driven schedule, same audio files).
//   node scripts/sync-wrfm.mjs [path/to/wrfm-source]      (default: ../../wrfm-source, or $WRFM_SOURCE)
// Re-run after changing WRFM's songs, clips or schedule code; commit the result (src/site/wrfm/).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.resolve(process.argv[2] || process.env.WRFM_SOURCE || path.join(APP, "..", "..", "wrfm-source"));
const OUT = path.join(APP, "src", "site", "wrfm");
if (!fs.existsSync(path.join(SRC, "src", "utils", "broadcastSchedule.js"))) {
  console.error(`WRFM source not found at ${SRC} (pass its path, or set WRFM_SOURCE)`); process.exit(1);
}
fs.mkdirSync(OUT, { recursive: true });
const head = (what) => `// GENERATED by scripts/sync-wrfm.mjs from wrfm-source/${what} - do not edit here; edit WRFM and re-sync.\n`;
// the schedule module, with its data imports pointed at the copies next to it
let js = fs.readFileSync(path.join(SRC, "src", "utils", "broadcastSchedule.js"), "utf8");
js = js.replace('"../../wrfm_songs.json"', '"./wrfm_songs.json"').replace('"../../wrfm_station.json"', '"./wrfm_station.json"')
       .replace('"../../wrfm_chatter_extension.json"', '"./wrfm_chatter_extension.json"');
fs.writeFileSync(path.join(OUT, "broadcastSchedule.js"), head("src/utils/broadcastSchedule.js") + js);
const copies = [["wrfm_songs.json", "wrfm_songs.json"], ["wrfm_station.json", "wrfm_station.json"],
                ["wrfm_chatter_extension.json", "wrfm_chatter_extension.json"], ["src/utils/audioDurations.json", "audioDurations.json"]];
for (const [from, to] of copies) fs.copyFileSync(path.join(SRC, from), path.join(OUT, to));
// where the audio files are served from (CloudFront first, then IPFS gateways), as WRFM orders them
const assets = JSON.parse(fs.readFileSync(path.join(SRC, "doqi_assets.json"), "utf8"));
const g = assets.gateways || {}, d = assets.gateway_defaults || {};
const primary = d.wrfm_audio || d._default || "aws";
const order = [...new Set([g[primary], g.emerald, g.lighthouse, g.cloudflare, g.dweb, g.ipfs_io, g.pinata_public].filter(Boolean)
  .map((u) => (u.endsWith("/") ? u : u + "/")))];
fs.writeFileSync(path.join(OUT, "gateways.json"), JSON.stringify({ audio: order }, null, 1) + "\n");
let rev = "";
try { rev = fs.readFileSync(path.join(SRC, ".git", "HEAD"), "utf8").trim(); } catch { /* not a git checkout */ }
console.log(`synced WRFM schedule + data from ${SRC} ${rev ? `(${rev})` : ""} -> ${path.relative(APP, OUT)}; audio hosts: ${order.length}`);
