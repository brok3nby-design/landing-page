# ================================================================== utilities
def rgb(h):
    h = h.lstrip("#")
    return np.array([int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)], dtype=np.float32)


def noise(h, w, scale=8.0, seed=0, aniso=(1.0, 1.0)):
    """Tileable fractal-ish noise in 0..1 via FFT filtering. scale ~ feature count across."""
    rng = np.random.default_rng(seed)
    white = rng.standard_normal((h, w))
    fy = np.fft.fftfreq(h)[:, None] * h
    fx = np.fft.fftfreq(w)[None, :] * w
    f = np.sqrt((fx * aniso[0]) ** 2 + (fy * aniso[1]) ** 2)
    filt = np.exp(-(f / scale) ** 2)
    out = np.real(np.fft.ifft2(np.fft.fft2(white) * filt))
    out -= out.min()
    return (out / (out.max() + 1e-9)).astype(np.float32)


def smooth(x, a, b):
    t = np.clip((x - a) / (b - a + 1e-9), 0, 1)
    return t * t * (3 - 2 * t)


class Canvas:
    def __init__(self, w, h, color=(0, 0, 0)):
        self.w, self.h = w, h
        self.a = np.zeros((h, w, 4), np.float32)
        self.a[..., :3] = color
        self.a[..., 3] = 1
        self.yy, self.xx = np.mgrid[0:h, 0:w].astype(np.float32)

    # every shape takes an optional alpha `op` and colour
    def _blend(self, mask, color, op=1.0):
        m = (mask * op)[..., None]
        self.a[..., :3] = self.a[..., :3] * (1 - m) + np.asarray(color, np.float32) * m

    def rect(self, x0, y0, x1, y1, color, op=1.0):
        m = ((self.xx >= x0) & (self.xx < x1) & (self.yy >= y0) & (self.yy < y1)).astype(np.float32)
        self._blend(m, color, op)

    def circle(self, cx, cy, r, color, op=1.0, ring=None):
        d = np.sqrt((self.xx - cx) ** 2 + (self.yy - cy) ** 2)
        m = np.clip(r - d + 0.5, 0, 1)
        if ring:
            m *= np.clip(d - (r - ring) + 0.5, 0, 1)
        self._blend(m, color, op)

    def poly(self, pts, color, op=1.0):
        pts = np.asarray(pts, np.float32)
        x0, y0 = np.floor(pts.min(0)).astype(int)
        x1, y1 = np.ceil(pts.max(0)).astype(int) + 1
        x0, y0, x1, y1 = max(x0, 0), max(y0, 0), min(x1, self.w), min(y1, self.h)
        if x0 >= x1 or y0 >= y1:
            return
        X, Y = self.xx[y0:y1, x0:x1] + 0.5, self.yy[y0:y1, x0:x1] + 0.5
        inside = np.zeros(X.shape, bool)
        n = len(pts)
        for i in range(n):
            xi, yi = pts[i]
            xj, yj = pts[(i + 1) % n]
            cond = (yi > Y) != (yj > Y)
            xint = (xj - xi) * (Y - yi) / ((yj - yi) + 1e-12) + xi
            inside ^= cond & (X < xint)
        m = np.zeros((self.h, self.w), np.float32)
        m[y0:y1, x0:x1] = inside
        self._blend(m, color, op)

    def line(self, x0, y0, x1, y1, width, color, op=1.0):
        pad = width + 2
        bx0, by0 = int(max(min(x0, x1) - pad, 0)), int(max(min(y0, y1) - pad, 0))
        bx1, by1 = int(min(max(x0, x1) + pad, self.w)), int(min(max(y0, y1) + pad, self.h))
        if bx0 >= bx1 or by0 >= by1:
            return
        X, Y = self.xx[by0:by1, bx0:bx1], self.yy[by0:by1, bx0:bx1]
        dx, dy = x1 - x0, y1 - y0
        L2 = dx * dx + dy * dy + 1e-9
        t = np.clip(((X - x0) * dx + (Y - y0) * dy) / L2, 0, 1)
        d = np.sqrt((X - x0 - t * dx) ** 2 + (Y - y0 - t * dy) ** 2)
        m = np.zeros((self.h, self.w), np.float32)
        m[by0:by1, bx0:bx1] = np.clip(width / 2 - d + 0.5, 0, 1)
        self._blend(m, color, op)

    def vgrad(self, y0, y1, c0, c1, x0=0, x1=None):
        x1 = self.w if x1 is None else x1
        t = np.clip((self.yy - y0) / max(y1 - y0, 1), 0, 1)[..., None]
        col = np.asarray(c0) * (1 - t) + np.asarray(c1) * t
        m = ((self.yy >= y0) & (self.yy < y1) & (self.xx >= x0) & (self.xx < x1))[..., None]
        self.a[..., :3] = np.where(m, col, self.a[..., :3])

    def text(self, s, x, y, px, color, op=1.0):
        """5x7 pixel font; (x, y) = top-left; px = pixel size."""
        cx = x
        for ch in s.upper():
            g = FONT.get(ch, FONT[" "])
            for r, row in enumerate(g):
                for c, bit in enumerate(row):
                    if bit == "#":
                        self.rect(cx + c * px, y + r * px, cx + (c + 1) * px, y + (r + 1) * px, color, op)
            cx += 6 * px
        return cx

    def mul(self, arr):
        self.a[..., :3] *= arr[..., None] if arr.ndim == 2 else arr

    def downsample(self, f):
        h, w = self.h // f, self.w // f
        self.a = self.a[:h * f, :w * f].reshape(h, f, w, f, 4).mean((1, 3))
        self.h, self.w = h, w
        self.yy, self.xx = np.mgrid[0:h, 0:w].astype(np.float32)
        return self

    def save(self, name, non_color=False, path=None):
        os.makedirs(OUT, exist_ok=True)
        path = path or os.path.join(OUT, name + ".png")
        img = bpy.data.images.new(name, self.w, self.h, alpha=True)
        data = np.clip(self.a[::-1], 0, 1).astype(np.float32)
        img.pixels.foreach_set(data.ravel())
        img.filepath_raw = path
        img.file_format = 'PNG'
        img.save()
        if non_color:
            img.colorspace_settings.name = 'Non-Color'
        return img


