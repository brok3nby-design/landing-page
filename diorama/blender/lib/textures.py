# ================================================================== surface maps (from a base texture)
def _blur(a, sigma):
    if sigma <= 0:
        return a
    h, w = a.shape
    fy = np.fft.fftfreq(h)[:, None]
    fx = np.fft.fftfreq(w)[None, :]
    g = np.exp(-2 * (np.pi * sigma) ** 2 * (fx ** 2 + fy ** 2))
    return np.real(np.fft.ifft2(np.fft.fft2(a) * g)).astype(np.float32)


def _height(src, size, blur, invert):
    from . import artwork
    arr = artwork.load_rgba(os.path.join(OUT, src + ".png"), size=size)
    lum = arr[..., 0] * 0.299 + arr[..., 1] * 0.587 + arr[..., 2] * 0.114
    lum = _blur(lum, blur)
    return 1 - lum if invert else lum


def normal_map(name, src, strength=4.0, size=None, blur=0.8, invert=False):
    """Tangent-space normal map (OpenGL / glTF convention) from the luminance of `src`.
    Bright = raised (or dark = raised with invert). Tileable sources stay tileable."""
    hgt = _height(src, size, blur, invert)
    dx = (np.roll(hgt, -1, 1) - np.roll(hgt, 1, 1)) * 0.5
    drow = (np.roll(hgt, -1, 0) - np.roll(hgt, 1, 0)) * 0.5
    nx, ny = -dx * strength, drow * strength          # rows run downwards, +V runs up
    nz = np.ones_like(nx)
    ln = np.sqrt(nx * nx + ny * ny + nz * nz)
    c = Canvas(hgt.shape[1], hgt.shape[0])
    c.a[..., 0], c.a[..., 1], c.a[..., 2] = nx / ln * 0.5 + 0.5, ny / ln * 0.5 + 0.5, nz / ln * 0.5 + 0.5
    return c.save(name, non_color=True)


def roughness_map(name, src, base=0.55, amount=0.25, size=None, blur=1.0, invert=False):
    """Roughness variation from `src`: normalised luminance shifts roughness around `base`."""
    hgt = _height(src, size, blur, invert)
    hn = (hgt - hgt.mean()) / (hgt.std() + 1e-6)
    r = np.clip(base + amount * 0.5 * hn, 0.05, 1.0)
    c = Canvas(r.shape[1], r.shape[0])
    c.a[..., 0] = c.a[..., 1] = c.a[..., 2] = r
    return c.save(name, non_color=True)


def label_card(name, w, h, lines, bg, fg, accent=None, px=None, border=False):
    """Text label (cards, stickers, plates) with the pixel font, lines centred."""
    c = Canvas(w, h, rgb(bg))
    if border:
        c.rect(6, 6, w - 6, 9, rgb(fg), 0.8); c.rect(6, h - 9, w - 6, h - 6, rgb(fg), 0.8)
        c.rect(6, 6, 9, h - 6, rgb(fg), 0.8); c.rect(w - 9, 6, w - 6, h - 6, rgb(fg), 0.8)
    total = sum((l[1] if isinstance(l, tuple) else (px or 4)) * 9 for l in lines)
    y = (h - total) / 2
    for ln in lines:
        text, p = (ln if isinstance(ln, tuple) else (ln, px or 4))
        col = rgb(accent) if (accent and text.startswith("*")) else rgb(fg)
        text = text.lstrip("*")
        tw = len(text) * 6 * p - p
        c.text(text, (w - tw) / 2, y, p, col)
        y += 9 * p
    c.mul(0.95 + 0.06 * noise(h, w, 30, 41))
    return c.save(name)


