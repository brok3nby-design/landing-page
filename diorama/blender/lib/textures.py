def generate_all(force=False):
    """Produce every texture. Order of preference per texture:
       1. your image in diorama/custom/ (see lib/artwork.py for slot names)
       2. the code-painted default (re-painted only when missing, forced, or a custom image
          was removed/changed - tracked in assets/textures/_sources.json)
    Derived surface maps are rebuilt whenever their source changes. Returns name -> bpy image."""
    from . import artwork
    os.makedirs(OUT, exist_ok=True)
    man_path = os.path.join(OUT, "_sources.json")
    manifest = json.load(open(man_path)) if os.path.exists(man_path) else {}
    changed = set()
    for name, job in JOBS.items():
        path = os.path.join(OUT, name + ".png")
        sig = artwork.signature(name)
        if force or not os.path.exists(path) or manifest.get(name, "default") != sig:
            whole = artwork.whole_override(name)
            if whole:
                c = Canvas(1, 1)
                c.a = artwork.load_rgba(whole)
                c.h, c.w = c.a.shape[:2]
                img = c.save(name)
                print(f"texture {name}: custom image {os.path.basename(whole)}")
            else:
                img = job()
            bpy.data.images.remove(img)
            manifest[name] = sig
            changed.add(name)
    for name, (src, job) in DERIVED.items():
        path = os.path.join(OUT, name + ".png")
        if force or not os.path.exists(path) or src in changed:
            bpy.data.images.remove(job())
    json.dump(manifest, open(man_path, "w"), indent=1, sort_keys=True)
    out = {}
    for name in list(JOBS) + list(DERIVED):
        img = bpy.data.images.load(os.path.join(OUT, name + ".png"), check_existing=True)
        img.name = name
        if name in DERIVED:
            img.colorspace_settings.name = 'Non-Color'
        out[name] = img
    return out
