# ================================================================== wood family
def wood(name, light="#b8743c", dark="#7a4320", size=1024, rings=22, seed=1, streak=0.35):
    """Tileable wood grain; grain runs along U (image x)."""
    warp = noise(size, size, 4, seed, aniso=(1.0, 0.5)) - 0.5
    fib = noise(size, size, 90, seed + 1, aniso=(0.05, 1.0))
    v = np.mgrid[0:size, 0:size][0] / size
    f = (v * rings + warp * 0.9) % 1.0
    ring = smooth(f, 0.55, 0.75) * (1 - smooth(f, 0.85, 1.0))
    t = np.clip(0.3 + ring * 0.32 + (fib - 0.5) * streak * 2, 0, 1)
    c = Canvas(size, size)
    c.a[..., :3] = rgb(light) * (1 - t[..., None]) + rgb(dark) * t[..., None]
    c.mul(0.9 + 0.1 * noise(size, size, 6, seed + 2))
    return c.save(name)


def planks(name, size=1024, rows=8, seed=3):
    """Platform floor planks: rows along V, staggered end seams, per-plank tint."""
    rng = np.random.default_rng(seed)
    base = noise(size, size, 4, seed, aniso=(1.0, 0.5)) - 0.5
    fib = noise(size, size, 70, seed + 1, aniso=(0.07, 1.0))
    c = Canvas(size, size)
    rh = size // rows
    light, dark = rgb("#c27a40"), rgb("#7d4520")
    for r in range(rows):
        y0, y1 = r * rh, (r + 1) * rh
        cuts = sorted(rng.uniform(0, 1, 2) * size)
        segs = [(cuts[0], cuts[1]), (cuts[1], cuts[0] + size)]
        for s0, s1 in segs:
            tint = rng.uniform(0.82, 1.12)
            off = rng.uniform(0, 1)
            xs = c.xx[y0:y1]
            sel = ((xs >= s0) & (xs < s1)) | ((xs + size >= s0) & (xs + size < s1))
            v = (c.yy[y0:y1] - y0) / rh
            f = (v * 4 + off + base[y0:y1] * 0.6) % 1
            t = np.clip(0.3 + smooth(f, 0.5, 0.7) * 0.4 + (fib[y0:y1] - 0.5) * 0.6, 0, 1)
            col = (light * (1 - t[..., None]) + dark * t[..., None]) * tint
            c.a[y0:y1, :, :3] = np.where(sel[..., None], col, c.a[y0:y1, :, :3])
        c.rect(0, y0, size, y0 + 2, rgb("#3a1e0d"))                         # long seam
        for cx in cuts:
            c.rect(int(cx) % size, y0, int(cx) % size + 2, y1, rgb("#3a1e0d"))  # end seams
    return c.save(name)


