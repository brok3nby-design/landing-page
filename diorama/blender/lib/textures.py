def rug(name, w=1024, h=640, seed=5):
    red, dred = rgb("#7a1410"), rgb("#4a0b09")
    navy, cream, ochre, black = rgb("#1d1a2e"), rgb("#e6d2a8"), rgb("#c58a3a"), rgb("#140c0c")
    c = Canvas(w, h, red)
    # field motif lattice
    for gy in range(70, h - 60, 26):
        for gx in range(70 + (gy // 26 % 2) * 13, w - 60, 26):
            c.poly([(gx, gy - 5), (gx + 5, gy), (gx, gy + 5), (gx - 5, gy)], cream, 0.85)
            c.circle(gx + 13, gy, 1.6, ochre)
    # corner spandrels
    for sx, sy in ((80, 80), (w - 80, 80), (80, h - 80), (w - 80, h - 80)):
        c.circle(sx, sy, 105, navy)
        c.circle(sx, sy, 92, cream, ring=3)
        c.circle(sx, sy, 70, dred)
        for k in range(12):
            a = k * np.pi / 6
            c.circle(sx + np.cos(a) * 82, sy + np.sin(a) * 82, 5, ochre)
    # outer borders (drawn over spandrels to clip them)
    c.rect(0, 0, w, 48, black); c.rect(0, h - 48, w, h, black)
    c.rect(0, 0, 48, h, black); c.rect(w - 48, 0, w, h, black)
    for x in range(24, w, 22):
        for y in (24, h - 24):
            c.poly([(x, y - 9), (x + 9, y), (x, y + 9), (x - 9, y)], cream)
            c.circle(x, y, 3, red)
    for y in range(24, h, 22):
        for x in (24, w - 24):
            c.poly([(x, y - 9), (x + 9, y), (x, y + 9), (x - 9, y)], cream)
            c.circle(x, y, 3, red)
    for inset, col, th in ((48, cream, 4), (58, ochre, 3), (64, dred, 8)):
        c.rect(inset, inset, w - inset, inset + th, col); c.rect(inset, h - inset - th, w - inset, h - inset, col)
        c.rect(inset, inset, inset + th, h - inset, col); c.rect(w - inset - th, inset, w - inset, h - inset, col)
    # central lobed medallion
    cx, cy = w / 2, h / 2
    ang = np.arctan2(c.yy - cy, (c.xx - cx) / 1.35)
    rad = np.sqrt(((c.xx - cx) / 1.35) ** 2 + (c.yy - cy) ** 2)
    for R, col, lobes, amp in ((190, cream, 12, 0.10), (182, navy, 12, 0.10), (140, dred, 8, 0.14),
                               (128, ochre, 8, 0.14), (118, red, 8, 0.14), (70, navy, 8, 0.2),
                               (40, cream, 8, 0.25), (22, red, 4, 0.3)):
        edge = R * (1 + amp * np.cos(lobes * ang))
        c._blend(np.clip(edge - rad + 0.5, 0, 1), col)
    for k in range(16):
        a = k * np.pi / 8
        c.circle(cx + np.cos(a) * 160 * 1.35, cy + np.sin(a) * 160, 4, cream)
    # pendant ends
    for s in (-1, 1):
        c.poly([(cx + s * 250, cy), (cx + s * 330, cy - 40), (cx + s * 380, cy), (cx + s * 330, cy + 40)], navy)
        c.poly([(cx + s * 280, cy), (cx + s * 330, cy - 20), (cx + s * 355, cy), (cx + s * 330, cy + 20)], cream)
    # woven texture
    weave = 0.92 + 0.08 * ((c.xx % 3 < 1.5) ^ (c.yy % 3 < 1.5))
    c.mul(weave * (0.85 + 0.25 * noise(h, w, 20, seed)))
    return c.save(name)


def plaid(name, w=512, h=1024, seed=7):
    """Red plaid blanket with a cream geometric band across the middle."""
    red, dred, cream, black = rgb("#9a1a1c"), rgb("#4e0b0e"), rgb("#e9dcc0"), rgb("#1b1010")
    c = Canvas(w, h, red)
    for p in range(0, w, 128):
        c.rect(p + 40, 0, p + 88, h, dred, 0.7)
        c.rect(p + 60, 0, p + 66, h, cream, 0.8)
        c.rect(p + 10, 0, p + 14, h, black, 0.6)
    for p in range(0, h, 128):
        c.rect(0, p + 40, w, p + 88, dred, 0.55)
        c.rect(0, p + 60, w, p + 66, cream, 0.7)
        c.rect(0, p + 10, w, p + 14, black, 0.5)
    for band_y in (h * 0.36, h * 0.64):
        y0 = int(band_y) - 50
        c.rect(0, y0, w, y0 + 100, cream)
        c.rect(0, y0 + 6, w, y0 + 10, black); c.rect(0, y0 + 90, w, y0 + 94, black)
        for x in range(0, w + 40, 40):
            c.poly([(x, y0 + 20), (x + 20, y0 + 50), (x, y0 + 80), (x - 20, y0 + 50)], red)
            c.poly([(x, y0 + 36), (x + 9, y0 + 50), (x, y0 + 64), (x - 9, y0 + 50)], cream)
            c.circle(x + 20, y0 + 50, 4, black)
    twill = 0.9 + 0.1 * (((c.xx + c.yy) % 4) < 2)
    c.mul(twill * (0.9 + 0.15 * noise(h, w, 30, seed)))
    return c.save(name)


def leather(name, size=512, seed=9, base="#1c1512"):
    c = Canvas(size, size, rgb(base))
    c.mul(0.75 + 0.4 * noise(size, size, 4, seed))
    c.mul(0.9 + 0.12 * noise(size, size, 120, seed + 1))
    return c.save(name)


def quilt(name, size=256, base="#a8743f", seed=11):
    c = Canvas(size, size, rgb(base))
    for k in range(-size, size * 2, 64):
        c.line(k, 0, k + size, size, 3, rgb("#6e4522"), 0.8)
        c.line(k, size, k + size, 0, 3, rgb("#6e4522"), 0.8)
    c.mul(0.88 + 0.2 * noise(size, size, 40, seed))
    return c.save(name)


def fabric(name, base="#4a4846", size=256, seed=13):
    c = Canvas(size, size, rgb(base))
    weave = 0.85 + 0.15 * ((c.xx % 4 < 2) ^ (c.yy % 4 < 2))
    c.mul(weave * (0.9 + 0.15 * noise(size, size, 25, seed)))
    return c.save(name)


