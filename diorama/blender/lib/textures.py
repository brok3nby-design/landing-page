def deskmat(name, w=1024, h=384):
    c = Canvas(w, h, rgb("#16110f"))
    orange, dor = rgb("#d9772b"), rgb("#7a3a12")
    c.rect(10, 10, w - 10, 14, orange, 0.8); c.rect(10, h - 14, w - 10, h - 10, orange, 0.8)
    c.rect(10, 10, 14, h - 10, orange, 0.8); c.rect(w - 14, 10, w - 10, h - 10, orange, 0.8)
    for cx, cy in ((0, 0), (w, 0), (0, h), (w, h), (w * 0.62, h * 0.55)):
        for r, op in ((150, 0.5), (120, 0.0)):
            pass
        for k in range(16):
            a = k * np.pi / 8
            for rr, sz in ((60, 16), (100, 12), (135, 8)):
                c.circle(cx + np.cos(a) * rr, cy + np.sin(a) * rr, sz, orange if rr != 100 else dor, 0.85)
        c.circle(cx, cy, 40, dor, 0.9)
        c.circle(cx, cy, 30, orange, 0.9, ring=4)
    c.mul(0.9 + 0.12 * noise(h, w, 50, 15))
    return c.save(name)


def _landscape(c, x0, y0, x1, y1, castle=False, seed=0):
    """Painterly sunset scene in the rectangle (pixel coords)."""
    rng = np.random.default_rng(seed)
    W, H = x1 - x0, y1 - y0
    hz = y0 + H * 0.62
    c.vgrad(y0, hz, rgb("#2b1c5c"), rgb("#ff8a5c"), x0, x1)
    c.vgrad(hz, y1, rgb("#3a2160"), rgb("#140c26"), x0, x1)
    sun_x = x0 + W * (0.55 if castle else 0.62)
    c.circle(sun_x, hz - H * 0.02, H * 0.09, rgb("#ffd27a"))
    c.circle(sun_x, hz - H * 0.02, H * 0.16, rgb("#ffb070"), 0.25)
    # clouds
    for k in range(5):
        cy = y0 + H * rng.uniform(0.12, 0.4)
        cx = x0 + W * rng.uniform(0.05, 0.9)
        for j in range(4):
            c.circle(cx + j * W * 0.03, cy + rng.uniform(-3, 3), H * rng.uniform(0.03, 0.05),
                     rgb("#ff9fb0"), 0.5)
    # mountain layers
    for layer, (col, amp, base) in enumerate(((rgb("#7a4a9a"), 0.22, 0.58), (rgb("#4e2f78"), 0.16, 0.64),
                                              (rgb("#2c1b4c"), 0.10, 0.70))):
        xs = np.linspace(x0, x1, 24)
        ys = y0 + H * (base - amp * np.abs(np.sin(np.linspace(0, 3.3, 24) * (1.3 + layer) + layer * 2.1)))
        c.poly([(x0, y1)] + list(zip(xs, ys)) + [(x1, y1)], col)
    if castle:
        cx, by = x0 + W * 0.5, y0 + H * 0.66
        dark = rgb("#1d1130")
        c.poly([(cx - W * 0.22, by + H * 0.06), (cx - W * 0.08, by - H * 0.12), (cx + W * 0.10, by - H * 0.12),
                (cx + W * 0.24, by + H * 0.06)], rgb("#3b2350"))
